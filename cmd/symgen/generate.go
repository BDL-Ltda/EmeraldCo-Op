package main

import (
	"bufio"
	"bytes"
	"crypto/sha1"
	"debug/elf"
	"fmt"
	"hash/crc32"
	"io"
	"sort"
	"strings"
)

func generate(elfReader io.ReaderAt, romReader io.Reader, allowlist io.Reader) ([]byte, error) {
	names, err := readAllowlist(allowlist)
	if err != nil {
		return nil, err
	}
	file, err := elf.NewFile(elfReader)
	if err != nil {
		return nil, fmt.Errorf("read ELF: %w", err)
	}
	if file.Class != elf.ELFCLASS32 || file.Data != elf.ELFDATA2LSB || file.Machine != elf.EM_ARM || file.Type != elf.ET_EXEC {
		return nil, fmt.Errorf("expected an ELF32 little-endian ARM executable; got %s, %s, %s, %s", file.Class, file.Data, file.Machine, file.Type)
	}
	symbols, err := file.Symbols()
	if err != nil {
		return nil, fmt.Errorf("read ELF symbols: %w", err)
	}
	wanted := make(map[string]bool, len(names))
	for _, name := range names {
		wanted[name] = true
	}
	found := make(map[string]elf.Symbol, len(names))
	for _, symbol := range symbols {
		if !wanted[symbol.Name] || symbol.Section == elf.SHN_UNDEF {
			continue
		}
		if previous, ok := found[symbol.Name]; ok && (previous.Value != symbol.Value || previous.Size != symbol.Size) {
			return nil, fmt.Errorf("symbol %q has conflicting definitions", symbol.Name)
		}
		found[symbol.Name] = symbol
	}
	for _, name := range names {
		if _, ok := found[name]; !ok {
			return nil, fmt.Errorf("symbol %q is missing or undefined in ELF", name)
		}
	}

	// SHA1 and CRC32 identify the supplied ROM; neither is a security primitive.
	// The client compares romCrc32, the only ROM hash mGBA 0.10.5 scripts can
	// get (emu:checksum); romSha1 is for humans and release notes.
	hash := sha1.New()
	crc := crc32.NewIEEE()
	if _, err := io.Copy(io.MultiWriter(hash, crc), romReader); err != nil {
		return nil, fmt.Errorf("hash ROM: %w", err)
	}
	var output bytes.Buffer
	fmt.Fprintln(&output, "-- GENERATED by cmd/symgen. DO NOT EDIT.")
	fmt.Fprintln(&output, "return {")
	fmt.Fprintf(&output, "  romSha1 = \"%x\",\n", hash.Sum(nil))
	fmt.Fprintf(&output, "  romCrc32 = \"%08x\",\n", crc.Sum32())
	fmt.Fprintln(&output, "  symbols = {")
	for _, name := range names {
		symbol := found[name]
		fmt.Fprintf(&output, "    [%q] = { addr = 0x%08X, size = %d },\n", name, symbol.Value, symbol.Size)
	}
	fmt.Fprintln(&output, "  },")
	fmt.Fprintln(&output, "}")
	return output.Bytes(), nil
}

func readAllowlist(reader io.Reader) ([]string, error) {
	var names []string
	seen := make(map[string]bool)
	scanner := bufio.NewScanner(reader)
	for line := 1; scanner.Scan(); line++ {
		name, _, _ := strings.Cut(scanner.Text(), "#")
		name = strings.TrimSpace(name)
		if name == "" {
			continue
		}
		if !isIdentifier(name) {
			return nil, fmt.Errorf("symbol allowlist line %d: invalid symbol name %q", line, name)
		}
		if seen[name] {
			return nil, fmt.Errorf("symbol allowlist line %d: duplicate symbol %q", line, name)
		}
		seen[name] = true
		names = append(names, name)
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read symbol allowlist: %w", err)
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("symbol allowlist is empty")
	}
	sort.Strings(names)
	return names, nil
}

func isIdentifier(name string) bool {
	for i, char := range name {
		letter := char >= 'A' && char <= 'Z' || char >= 'a' && char <= 'z' || char == '_'
		if !letter && !(i > 0 && char >= '0' && char <= '9') {
			return false
		}
	}
	return name != ""
}
