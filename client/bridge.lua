-- Emerald Co-Op client entry point. Load it in mGBA 0.10.5:
-- Tools > Scripting... > File > Load script... > client/bridge.lua
--
-- Before doing anything else it loads config.lua and addresses.lua and checks
-- that the loaded ROM is the exact build addresses.lua was generated from. On
-- any problem it logs a clear error and stops; the game keeps running normally.

local DIR = debug.getinfo(1, "S").source:match("^@(.*[/\\])") or "./"

local function fail(msg)
	console:error("[bridge] " .. msg)
end

-- mGBA opens the script itself from any path, but Lua's own file functions
-- (io.open, loadfile, require) cannot open non-ASCII paths on Windows, e.g. a
-- user folder named "Usuário". Probe this file first so that case gets a clear
-- message instead of a misleading "not found".
local probe = io.open(DIR .. "bridge.lua", "rb")
if not probe then
	if DIR:find("[\128-\255]") then
		fail("Lua in mGBA cannot open files in this folder because its path has non-ASCII characters (" .. DIR ..
			"). Move the Emerald Co-Op folder to a path with only ASCII letters, e.g. C:\\EmeraldCoop, and load it again.")
	else
		fail("Lua in mGBA cannot open files in " .. DIR .. " Check the folder still exists and is readable.")
	end
	return
end
probe:close()

package.path = DIR .. "lib/?.lua;" .. package.path
local romcheck = require("romcheck")

-- loadfile instead of require: a missing file must be a friendly error, and a
-- reloaded script must read the current file, not a cached module.
local function loadTable(name, missingHint)
	local chunk, err = loadfile(DIR .. name)
	if not chunk then
		if tostring(err):match("^cannot open") then
			return nil, missingHint
		end
		return nil, name .. " has a syntax error: " .. tostring(err)
	end
	local ok, value = pcall(chunk)
	if not ok or type(value) ~= "table" then
		return nil, name .. " must return a table" .. (ok and "" or ": " .. tostring(value))
	end
	return value
end

local config, cerr = loadTable("config.lua",
	"config.lua not found. Copy client/config.example.lua to client/config.lua and fill it in.")
if not config then
	fail(cerr)
	return
end

local addresses, aerr = loadTable("addresses.lua",
	"addresses.lua not found. It is generated by cmd/symgen and committed; check your checkout.")
if not addresses then
	fail(aerr)
	return
end

-- Runs once a game is loaded, and again whenever another game is started, so
-- switching ROMs with the script still loaded is caught too. Later issues (#11
-- onward) start their work here, and only when the ROM is verified.
local function verifyRom()
	local ok, msg = romcheck.verify(addresses.romCrc32, emu:checksum())
	if ok then
		console:log("[bridge] " .. msg)
	else
		fail(msg)
	end
end

console:log("[bridge] Emerald Co-Op bridge started")
callbacks:add("start", verifyRom)
if emu then
	verifyRom()
end
